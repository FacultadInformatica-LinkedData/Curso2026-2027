"""**TASK 7.2a:**

Spanish: Enumera todos los individuos de "Person" con RDFLib (ten en cuenta las subclases). Devuelve los URI de los individuos en una lista llamada "individuals".

English: List all individuals of "Person" with RDFLib (remember the subClasses). Return the individual URIs in a list called "individuals"

"""

ns = Namespace("http://oeg.fi.upm.es/def/people#")

# variable to return
individuals = []

#TODO
# Obtener todas las clases que son Person o subclases
person_classes = {ns.Person}
# Buscar las subclases recursivamente en el grafo
for cls in g.subjects(RDFS.subClassOf, ns.Person):
    person_classes.add(cls)
    for sub_cls in g.subjects(RDFS.subClassOf, cls):
        person_classes.add(sub_cls)
        for sub_sub_cls in g.subjects(RDFS.subClassOf, sub_cls):
            person_classes.add(sub_sub_cls)

# Recoger todos los individuos que pertenezcan a cualquiera de estas clases
for prs_class in person_classes:
    for individuo in g.subjects(RDF.type, prs_class):
        if individuo not in individuals:
            individuals.append(individuo)

# visualize results
for i in individuals:
    print(i)

# validation. Do not remove
report.validate_07_02a(individuals)

